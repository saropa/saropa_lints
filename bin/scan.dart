/// Standalone lint scanner that runs saropa_lints rules against any Dart
/// project without requiring it as a dependency.
///
/// Reads the project's analysis_options.yaml (generated by `init`) to
/// determine which rules are enabled, unless --tier is used. If no config
/// exists and no --tier is given, prompts the user to run `init` first.
///
/// Usage:
///   dart run saropa_lints scan [path]
///   dart run saropa_lints:scan [path]
///
/// Exit codes:
///   0 - No issues found (or none at/above --fail-on threshold)
///   1 - Issues found (or at least one at/above --fail-on threshold)
///   2 - No configuration found / invalid tier / parse error
Future<void> main(List<String> args) async {
  if (args.contains('--help') || args.contains('-h')) {
    _printUsage();

    return;
  }

  final result = parseScanArgs(args, readStdin: _readStdinLines);
  if (result is ScanParseInvalid) {
    print(result.message);
    exit(2);
  }
  // Fix: avoid_unsafe_cast — the preceding `is ScanParseInvalid` guard plus
  // the only-other-subtype ScanParseOk means this cast is statically safe,
  // but using a pattern-matched branch satisfies the lint and documents it.
  if (result is! ScanParseOk) {
    stderr.writeln('Unexpected scan parse result: ${result.runtimeType}');
    exit(2);
  }

  final parsed = result.args;
  final path = parsed.path;
  final dartFiles = parsed.dartFiles;
  final tier = parsed.tier;
  final formatJson = parsed.formatJson;
  // --quiet: suppress non-fatal stderr messages so automation sees only the
  // exit code + stdout output. Fatal errors (exit 2) still go to stderr.
  final quiet = parsed.quiet;

  if (parsed.fixIgnores) {
    _runFixIgnores(path);
    exit(0);
  }

  // --check-sdk-compat: standalone SDK compatibility audit, then exit.
  if (parsed.checkSdkCompat) {
    final result = checkSdkCompat(path, quiet: quiet);
    if (result == null) exit(2);
    stdout.write(formatSdkCompatResult(result));
    // Exit 1 if there's a mismatch, 0 if OK.
    exit(result.hasMismatch ? 1 : 0);
  }

  // --profile: arm per-rule timing capture BEFORE any rule callback runs and
  // start from a clean tracker so the report reflects only this run. This is
  // the runtime path (not the SAROPA_LINTS_PROFILE dart-define) so `dart run`
  // snapshot caching can never silently disable it.
  if (parsed.profile) {
    RuleTimingTracker.reset();
    SaropaContext.runtimeProfilingEnabled = true;
  }

  // --quiet: suppress ALL stderr progress/status from the scanner by routing
  // messages to a no-op sink. The caller gets only the exit code + stdout.
  final runner = ScanRunner(
    targetPath: path,
    dartFiles: dartFiles.isEmpty ? null : dartFiles,
    tier: tier,
    debugRule: parsed.debugRule,
    excludeLightLane: parsed.excludeLightLane,
    // --lane full|light: explicit lane override. parseRuleLane handles null
    // (defaults to light for the plugin, but ScanRunner defaults to full).
    lane: parseRuleLane(parsed.lane ?? 'full'),
    laneStats: parsed.laneStats,
    messageSink: parsed.quiet ? (_) {} : null,
    // Keep the IDE issue cap — scan output may feed the Problems tab.
    // disableIssueCap: false (default),
    excludeGlobs: parsed.excludeGlobs,
    includeGlobs: parsed.includeGlobs,
  );
  // --resolve runs the slower, fully-resolved scan so that
  // InstanceCreationExpression and type-based rules actually fire; the default
  // path stays the fast syntactic parse.
  final diagnostics = parsed.resolve
      ? await runner.runResolved()
      : runner.run();

  // Flush the timing profile even when diagnostics is null (config error):
  // by that point rules may already have run, and a partial profile beats a
  // silently discarded one. Written to stderr so --format json stdout stays
  // machine-parseable.
  if (parsed.profile) {
    final timingPath = writeRuleTimingReport(
      projectRoot: path,
      tier: tier,
      resolved: parsed.resolve,
      fileCount: dartFiles.isEmpty ? null : dartFiles.length,
    );
    if (timingPath != null) {
      if (!quiet) stderr.writeln('Timing profile: $timingPath');
    } else {
      // An empty tracker after a profiled run means no rule callbacks
      // executed — surface it, never let profiling fail silently again.
      if (!quiet) stderr.writeln('Timing profile: no data collected (no rules ran).');
    }
  }

  if (diagnostics == null) {
    exit(2);
  }

  // --find-stale-ignores: detect ignore comments whose suppressed rule no
  // longer fires. Runs AFTER the scan so we have the full diagnostic set to
  // diff against the ignore directives in the source files.
  if (parsed.findStaleIgnores) {
    _runFindStaleIgnores(
      diagnostics,
      path,
      dartFiles,
      formatJson,
      parsed.jsonFilePath,
      quiet,
    );
    // _runFindStaleIgnores calls exit() internally.
  }

  // --fix-stale-ignores: detect stale ignores AND automatically remove them
  // from the source files. Runs the same detection as --find-stale-ignores,
  // then writes the cleaned files back to disk.
  if (parsed.fixStaleIgnores) {
    _runFixStaleIgnores(diagnostics, path, dartFiles, quiet);
    // _runFixStaleIgnores calls exit() internally.
  }

  // Warn about unrecognized severity values so a future analyzer change
  // doesn't silently drop diagnostics through the rank-0 fallback.
  if (parsed.minSeverity != null) {
    final unknown = diagnostics
        .map((d) => d.severity.toUpperCase())
        .where((s) => !_knownSeverities.contains(s))
        .toSet();
    for (final s in unknown) {
      if (!quiet) stderr.writeln('Warning: unrecognized severity "$s" — excluded by filter.');
    }
  }

  // Apply --min-severity / --max-severity / --min-impact filters to exclude
  // diagnostics outside the requested window.
  final hasFilter = parsed.minSeverity != null ||
      parsed.maxSeverity != null ||
      parsed.minImpact != null;
  final filtered = hasFilter
      ? diagnostics.where((d) {
          final rank = _severityRank(d.severity);
          if (parsed.minSeverity != null &&
              rank < _severityRank(parsed.minSeverity!)) {
            return false;
          }
          if (parsed.maxSeverity != null &&
              rank > _severityRank(parsed.maxSeverity!)) {
            return false;
          }
          // Impact filter: uses the same rank scale as severity but against the
          // rule-declared impact. Diagnostics with no impact (non-saropa rules)
          // are excluded when a minimum impact is set, since they cannot be
          // classified.
          if (parsed.minImpact != null) {
            final impact = d.impact;
            if (impact == null ||
                _severityRank(impact) < _severityRank(parsed.minImpact!)) {
              return false;
            }
          }
          return true;
        }).toList()
      : diagnostics;

  // --fail-on / --fail-on-impact decouple exit code from display filtering:
  // the exit code is determined by whether any diagnostic in the FULL set meets
  // the threshold, not by what survived the display filter.
  // Build the tier rule set once if --fail-on-tier is active, so the exit-code
  // check doesn't recompute it per diagnostic.
  final failOnTierRules = parsed.failOnTier != null
      ? getRulesForTier(parsed.failOnTier!)
      : null;

  final exitCode = _computeExitCode(
    filtered: filtered,
    allDiagnostics: diagnostics,
    failOn: parsed.failOn,
    failOnImpact: parsed.failOnImpact,
    failOnTierRules: failOnTierRules,
    failOnCount: parsed.failOnCount,
    failOnImpactCount: parsed.failOnImpactCount,
  );

  // Build --fail-on metadata for JSON output so consumers understand why
  // the exit code may disagree with an empty diagnostics array.
  // BREAKING for consumers that check `failOn == null`: this object is now
  // non-null when --fail-on-impact or --fail-on-tier is used alone. The
  // `threshold` key is still absent in that case — check for it specifically.
  final failOnMeta = parsed.failOn != null ||
          parsed.failOnImpact != null ||
          parsed.failOnTier != null
      ? <String, Object>{
          // Severity threshold (original --fail-on).
          if (parsed.failOn != null) 'threshold': parsed.failOn!,
          // Impact threshold (new --fail-on-impact).
          if (parsed.failOnImpact != null)
            'impactThreshold': parsed.failOnImpact!,
          // Tier threshold (--fail-on-tier).
          if (parsed.failOnTier != null)
            'tierThreshold': parsed.failOnTier!,
          'thresholdMet': exitCode == 1,
          // Include the count baselines when active.
          if (parsed.failOnCount != null)
            'countBaseline': parsed.failOnCount!,
          if (parsed.failOnImpactCount != null)
            'impactCountBaseline': parsed.failOnImpactCount!,
        }
      : null;

  if (filtered.isEmpty) {
    if (!formatJson) {
      // Distinguish "genuinely clean" from "all outside window" so callers
      // (AI agents, CI) know diagnostics were suppressed, not absent.
      if (hasFilter && diagnostics.isNotEmpty) {
        print(
          '\nNo issues in the requested filter window '
          '(${diagnostics.length} outside threshold).',
        );
      } else {
        print('\nNo issues found.');
      }
    }
    // When a --fail-on* flag causes a non-zero exit despite no displayed
    // diagnostics, explain so automation doesn't see "No issues" + exit 1.
    if (!formatJson && exitCode != 0 &&
        (parsed.failOn != null || parsed.failOnImpact != null ||
         parsed.failOnTier != null)) {
      final reasons = [
        if (parsed.failOn != null)
          '--fail-on ${parsed.failOn!.toLowerCase()}',
        if (parsed.failOnImpact != null)
          '--fail-on-impact ${parsed.failOnImpact!.toLowerCase()}',
        if (parsed.failOnTier != null)
          '--fail-on-tier ${parsed.failOnTier!}',
      ];
      print(
        '(exit 1: ${reasons.join(' or ')} threshold met '
        'in unfiltered diagnostics)',
      );
    }
    if (formatJson) {
      _writeJson(scanDiagnosticsToJsonString(filtered, failOn: failOnMeta), parsed.jsonFilePath, quiet: quiet);
    }
    exit(exitCode);
  }

  if (formatJson) {
    _writeJson(scanDiagnosticsToJsonString(filtered, failOn: failOnMeta), parsed.jsonFilePath, quiet: quiet);
    exit(exitCode);
  }

  final reportPath = _writeReport(filtered, path);
  _printSummary(filtered);
  print('Report: $reportPath');
  exit(exitCode);
}

/// Reads stdin until EOF; returns non-empty trimmed lines (for --files-from-stdin).
List<String> _readStdinLines() {
  final lines = <String>[];
  String? line;
  while ((line = stdin.readLineSync()) != null) {
    final trimmed = line!.trim();
    if (trimmed.isNotEmpty) lines.add(trimmed);
  }
  return lines;
}

/// Write detailed results to a report file. Returns the file path.
String _writeReport(List<ScanDiagnostic> diagnostics, String targetPath) {
  // Fix: prefer_utc_for_storage — report timestamps are written to files and
  // consumed across time zones; UTC keeps filename ordering stable.
  final now = DateTime.now().toUtc();
  final ts =
      '${now.year}${now.month.toString().padLeft(2, '0')}${now.day.toString().padLeft(2, '0')}_'
      '${now.hour.toString().padLeft(2, '0')}${now.minute.toString().padLeft(2, '0')}${now.second.toString().padLeft(2, '0')}';
  final dateFolder = ts.prefix(8);

  final reportsDir = Directory('reports/$dateFolder');
  if (!reportsDir.existsSync()) {
    reportsDir.createSync(recursive: true);
  }

  final reportFile = File('${reportsDir.path}/${ts}_scan_report.log');

  final buf = StringBuffer();
  buf.writeln('${'=' * 80}');
  buf.writeln('SAROPA LINTS SCAN REPORT');
  // Fix: prefer_utc_for_storage — explicit .toUtc() at the call site so the
  // rule can see timezone normalization at the storage-adjacent usage.
  buf.writeln('Generated: ${now.toUtc().toIso8601String()}');
  buf.writeln('Target: ${p.absolute(targetPath)}');
  buf.writeln('Total issues: ${diagnostics.length}');
  buf.writeln('${'=' * 80}');
  buf.writeln();

  // Group by file
  final byFile = <String, List<ScanDiagnostic>>{};
  for (final d in diagnostics) {
    byFile.putIfAbsent(d.filePath, () => []).add(d);
  }

  for (final entry in byFile.entries) {
    buf.writeln(entry.key);
    for (final d in entry.value) {
      // Default nullable problemMessage to empty string (avoid_nullable_interpolation).
      buf.writeln(
        '  ${d.severity.padRight(7)} '
        'line ${d.line.toString().padLeft(4)}  '
        '${d.ruleName}  ${d.problemMessage ?? ''}',
      );
    }
    buf.writeln();
  }

  // Summary by rule
  buf.writeln('${'─' * 80}');
  buf.writeln('ISSUES BY RULE');
  buf.writeln('${'─' * 80}');
  final byRule = <String, int>{};
  for (final d in diagnostics) {
    byRule[d.ruleName] = (byRule[d.ruleName] ?? 0) + 1;
  }

  final sortedRules = byRule.entries.toList()
    ..sort((a, b) => b.value.compareTo(a.value));
  for (final entry in sortedRules) {
    buf.writeln('  ${entry.value.toString().padLeft(6)}  ${entry.key}');
  }

  reportFile.writeAsStringSync(buf.toString());
  return reportFile.path;
}

/// Print a compact summary to terminal.
void _printSummary(List<ScanDiagnostic> diagnostics) {
  // Count by severity
  final bySeverity = <String, int>{};
  for (final d in diagnostics) {
    bySeverity[d.severity] = (bySeverity[d.severity] ?? 0) + 1;
  }

  // Count by rule (for top offenders)
  final byRule = <String, int>{};
  for (final d in diagnostics) {
    byRule[d.ruleName] = (byRule[d.ruleName] ?? 0) + 1;
  }

  // Count files affected
  final fileCount = diagnostics.map((d) => d.filePath).toSet().length;

  print('');
  print('${diagnostics.length} issue(s) in $fileCount file(s)');

  final parts = <String>[];
  for (final sev in ['ERROR', 'WARNING', 'INFO']) {
    final count = bySeverity[sev];
    if (count != null && count > 0) {
      parts.add('$count ${sev.toLowerCase()}');
    }
  }
  if (parts.isNotEmpty) {
    print('  ${parts.join(' · ')}');
  }

  // Top 10 rules
  final sortedRules = byRule.entries.toList()
    ..sort((a, b) => b.value.compareTo(a.value));
  final top = sortedRules.take(10);
  print('');
  print('Top rules:');
  for (final entry in top) {
    print('  ${entry.value.toString().padLeft(6)}  ${entry.key}');
  }
  if (sortedRules.length > 10) {
    print('  ... and ${sortedRules.length - 10} more (see report)');
  }
  print('');
}

void _runFixIgnores(String targetPath) {
  final allRules = getAllDefinedRules();
  final results = convertIgnoreComments(
    allRules,
    false,
    targetDir: p.canonicalize(targetPath),
  );
  if (results.isEmpty) {
    print('No bare ignore comments found.');
    return;
  }
  final total = results.values.fold(0, (s, c) => s + c);
  print('Converted $total ignore comments in ${results.length} files:');
  for (final entry in results.entries) {
    print('  ${entry.value} in ${p.relative(entry.key)}');
  }
}

/// Detects stale `// ignore:` comments by comparing ignore directives against
/// the diagnostics the scan actually produced. An ignore is stale when its rule
/// did not fire on the target line — the code was fixed but the ignore remains.
///
/// Resolves the file list the same way the scanner does: from [dartFiles] if
/// specified, otherwise by discovering all `.dart` files under [targetPath].
void _runFindStaleIgnores(
  List<ScanDiagnostic> diagnostics,
  String targetPath,
  List<String> dartFiles,
  bool formatJson,
  String? jsonFilePath,
  bool quiet,
) {
  // Resolve the scanned file list so we can parse ignore comments from every
  // file the scan covered — including files with zero diagnostics.
  final files = dartFiles.isNotEmpty
      ? dartFiles
          .map(
            (f) => p.isAbsolute(f) ? p.normalize(f) : p.normalize(p.join(p.absolute(targetPath), f)),
          )
          .where((f) => f.endsWith('.dart'))
          .toList()
      : ScanRunner.discoverDartFiles(p.absolute(targetPath));

  final stale = detectStaleIgnores(diagnostics: diagnostics, files: files);

  if (formatJson) {
    _writeJson(staleIgnoresToJsonString(stale), jsonFilePath, quiet: quiet);
    exit(stale.isEmpty ? 0 : 1);
  }

  if (stale.isEmpty) {
    print('\nNo stale ignore comments found.');
    exit(0);
  }

  // Group by file for readable text output.
  final byFile = <String, List<StaleIgnore>>{};
  for (final s in stale) {
    byFile.putIfAbsent(s.filePath, () => []).add(s);
  }

  final fileCount = byFile.length;
  print('');
  print('${stale.length} stale ignore(s) in $fileCount file(s):');
  print('');

  for (final entry in byFile.entries) {
    print(p.relative(entry.key, from: targetPath));
    for (final s in entry.value) {
      print(
        '  line ${s.commentLine.toString().padLeft(4)}  '
        '${s.ruleName}  (target line ${s.targetLine})',
      );
    }
    print('');
  }

  // Top rules summary for quick triage.
  final byRule = <String, int>{};
  for (final s in stale) {
    byRule[s.ruleName] = (byRule[s.ruleName] ?? 0) + 1;
  }
  final sortedRules = byRule.entries.toList()
    ..sort((a, b) => b.value.compareTo(a.value));
  print('By rule:');
  for (final entry in sortedRules) {
    print('  ${entry.value.toString().padLeft(6)}  ${entry.key}');
  }
  print('');

  exit(1);
}

/// Detects stale `// ignore:` comments and automatically removes them from
/// the source files. Prints a summary of what was fixed.
///
/// Uses the same file-resolution logic as [_runFindStaleIgnores] so the
/// detection covers the same set of files the scan analyzed.
void _runFixStaleIgnores(
  List<ScanDiagnostic> diagnostics,
  String targetPath,
  List<String> dartFiles,
  bool quiet,
) {
  // Resolve the scanned file list identically to _runFindStaleIgnores.
  final files = dartFiles.isNotEmpty
      ? dartFiles
          .map(
            (f) => p.isAbsolute(f) ? p.normalize(f) : p.normalize(p.join(p.absolute(targetPath), f)),
          )
          .where((f) => f.endsWith('.dart'))
          .toList()
      : ScanRunner.discoverDartFiles(p.absolute(targetPath));

  final stale = detectStaleIgnores(diagnostics: diagnostics, files: files);

  if (stale.isEmpty) {
    print('\nNo stale ignore comments found. Nothing to fix.');
    exit(0);
  }

  // Apply the fixes — removes stale directives from source files.
  final results = fixStaleIgnores(stale);

  if (results.isEmpty) {
    // Detection found stale ignores but the fixer couldn't modify any files
    // (e.g. files were deleted between detection and fix).
    print('\nDetected ${stale.length} stale ignore(s) but no files were modified.');
    exit(1);
  }

  // Summary: total removed and files touched.
  final totalRemoved = results.fold(0, (sum, r) => sum + r.removedCount);
  final fileCount = results.length;
  print('');
  print('Fixed $totalRemoved stale ignore(s) in $fileCount file(s):');
  print('');
  for (final r in results) {
    print('  ${r.removedCount} removed in ${p.relative(r.filePath, from: targetPath)}');
  }
  print('');

  exit(0);
}

/// Writes JSON output to [filePath] if set, otherwise prints to stdout.
/// Using a file avoids the stdout-redirection problem entirely (#310).
/// Creates parent directories if they don't exist — fail-fast on
/// permission errors, but don't force callers to mkdir first.
void _writeJson(String json, String? filePath, {bool quiet = false}) {
  if (filePath != null) {
    final file = File(filePath);
    final parent = file.parent;
    if (!parent.existsSync()) {
      parent.createSync(recursive: true);
    }
    file.writeAsStringSync(json);
    if (!quiet) stderr.writeln('JSON written to: $filePath');
  } else {
    print(json);
  }
}

/// Known severity strings emitted by the analyzer diagnostic system.
const _knownSeverities = {'ERROR', 'WARNING', 'INFO'};

/// Severity rank for ordering/filtering: higher = more severe.
/// The fallback `_ => 0` handles the analyzer's NONE severity (never used in
/// practice for diagnostics) — such entries are excluded by any filter, which
/// is safe because no real lint rule emits NONE.
int _severityRank(String severity) => switch (severity.toUpperCase()) {
  'ERROR' => 3,
  'WARNING' => 2,
  'INFO' => 1,
  _ => 0,
};

/// Returns true if [severity] is at or above [minSeverity].
bool _meetsMinSeverity(String severity, String minSeverity) =>
    _severityRank(severity) >= _severityRank(minSeverity);

/// Determines exit code based on diagnostics and the optional --fail-on /
/// --fail-on-impact thresholds.
///
/// Without either: exit 1 when any filtered diagnostic exists (existing
/// behavior). With --fail-on: exit 1 when the FULL diagnostic list has enough
/// entries at/above the severity threshold. With --fail-on-impact: same logic
/// but checks the rule's declared impact instead. When both are set, either
/// threshold being met triggers exit 1 (logical OR — strictest wins).
/// [failOnCount] applies to --fail-on (severity count baseline).
/// [failOnImpactCount] applies to --fail-on-impact (impact count baseline).
/// [failOnTierRules] is the pre-computed set from [getRulesForTier] when
/// --fail-on-tier is active — diagnostics whose ruleName is in this set
/// trigger exit 1.
int _computeExitCode({
  required List<ScanDiagnostic> filtered,
  required List<ScanDiagnostic> allDiagnostics,
  required String? failOn,
  String? failOnImpact,
  Set<String>? failOnTierRules,
  int? failOnCount,
  int? failOnImpactCount,
}) {
  // Track whether any threshold triggers a failure (logical OR).
  var triggered = false;

  if (failOn != null) {
    // Count diagnostics in the full set that meet the severity threshold.
    final matchCount =
        allDiagnostics.where((d) => _meetsMinSeverity(d.severity, failOn)).length;
    // Without --fail-on-count: any match → exit 1 (count > 0).
    // With --fail-on-count: exit 1 only when count exceeds the baseline.
    final threshold = failOnCount ?? 0;
    if (matchCount > threshold) triggered = true;
  }

  if (failOnImpact != null) {
    // Count saropa diagnostics whose rule-declared impact meets the threshold.
    // Non-saropa diagnostics (impact == null) are excluded — they have no
    // declared impact and cannot be classified on this axis.
    // Note: impact values come from LintImpact.name (lowercase: error/warning/info)
    // while failOnImpact is uppercased by the parser — _severityRank handles
    // both cases via .toUpperCase() internally.
    final impactMatchCount = allDiagnostics
        .where((d) => d.impact != null && _meetsMinSeverity(d.impact!, failOnImpact))
        .length;
    // Without --fail-on-impact-count: any match → exit 1 (count > 0).
    // With --fail-on-impact-count: exit 1 only when count exceeds baseline.
    final impactThreshold = failOnImpactCount ?? 0;
    if (impactMatchCount > impactThreshold) triggered = true;
  }

  if (failOnTierRules != null) {
    // Check if any diagnostic comes from a rule in the target tier.
    // Rule names in diagnostics use the bare name (no saropa_lints/ prefix),
    // which matches the tiers.dart sets.
    final tierMatchCount = allDiagnostics
        .where((d) => failOnTierRules.contains(d.ruleName))
        .length;
    if (tierMatchCount > 0) triggered = true;
  }

  // When any threshold is active, use the triggered result.
  if (failOn != null || failOnImpact != null || failOnTierRules != null) {
    return triggered ? 1 : 0;
  }

  // Default: any displayed diagnostic → exit 1.
  return filtered.isEmpty ? 0 : 1;
}

void _printUsage() {
  print('saropa_lints scan - Standalone lint scanner');
  print('');
  print('Runs the rules configured by "init" against any Dart project,');
  print('without requiring saropa_lints as a dependency in that project.');
