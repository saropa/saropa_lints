/// Standalone lint scanner that runs saropa_lints rules against any Dart
/// project without requiring it as a dependency.
///
/// Reads the project's analysis_options.yaml (generated by `init`) to
/// determine which rules are enabled, unless --tier is used. If no config
/// exists and no --tier is given, prompts the user to run `init` first.
///
/// Usage:
///   dart run saropa_lints scan [path]
///   dart run saropa_lints:scan [path]
///
/// Exit codes:
///   0 - No issues found (or none at/above --fail-on threshold)
///   1 - Issues found (or at least one at/above --fail-on threshold)
///   0 - Also returned (with a "scan skipped" line) when lint integration is
///       off, or a commented-out plugin block holds no rule settings
///   2 - No configuration found / invalid tier / parse error
Future<void> main(List<String> args) async {
  if (args.contains('--help') || args.contains('-h')) {
    _printUsage();

    return;
  }

  final result = parseScanArgs(args, readStdin: _readStdinLines);
  if (result is ScanParseInvalid) {
    print(result.message);
    exit(2);
  }
  // Fix: avoid_unsafe_cast — the preceding `is ScanParseInvalid` guard plus
  // the only-other-subtype ScanParseOk means this cast is statically safe,
  // but using a pattern-matched branch satisfies the lint and documents it.
  if (result is! ScanParseOk) {
    stderr.writeln('Unexpected scan parse result: ${result.runtimeType}');
    exit(2);
  }

  final parsed = result.args;
  final path = parsed.path;
  final dartFiles = parsed.dartFiles;
  final tier = parsed.tier;
  final formatJson = parsed.formatJson;
  // --quiet: suppress non-fatal stderr messages so automation sees only the
  // exit code + stdout output. Fatal errors (exit 2) still go to stderr.
  final quiet = parsed.quiet;

  if (parsed.fixIgnores) {
    _runFixIgnores(path);
    exit(0);
  }

  // --check-sdk-compat: standalone SDK compatibility audit, then exit.
  if (parsed.checkSdkCompat) {
    final result = checkSdkCompat(path, quiet: quiet);
    if (result == null) exit(2);
    stdout.write(formatSdkCompatResult(result));
    // Exit 1 if there's a mismatch, 0 if OK.
    exit(result.hasMismatch ? 1 : 0);
  }

  // Stale-ignore modes judge comments from an evidence-gated scan (see
  // runStaleIgnoreScan), never from the normal one.
  final staleMode = parsed.findStaleIgnores || parsed.fixStaleIgnores;

  // A plain scan (no tier) of a project whose plugin block is commented out.
  // Not for --check-accepted or the stale-ignore modes, which always run; the
  // stale check only removes a comment its own scan proved unneeded for a rule
  // that ran.
  if (tier == null && !parsed.checkAccepted && !staleMode) {
    _handleCommentedOutPluginBlock(p.absolute(path), quiet: quiet);
  }

  // --profile: arm per-rule timing capture BEFORE any rule callback runs and
  // start from a clean tracker so the report reflects only this run. This is
  // the runtime path (not the SAROPA_LINTS_PROFILE dart-define) so `dart run`
  // snapshot caching can never silently disable it.
  if (parsed.profile) {
    RuleTimingTracker.reset();
    SaropaContext.runtimeProfilingEnabled = true;
  }

  // `analyzer: exclude:` from the nearest analysis_options.yaml, then
  // --exclude-globs (#403). Built once; also used by the stale-ignore file
  // discovery so excluded files are never treated as scanned.
  final excludeGlobs = [...loadAnalyzerExcludes(path), ...parsed.excludeGlobs];

  // Non-error output is uncapped by default for the CLI: a silent cap makes
  // --fail-on-count thresholds and CI reports wrong. --max-issues N or the
  // SAROPA_LINTS_MAX env var (shared with the IDE plugin) opt back in. Held
  // in a local so --check-accepted can tell whether output may be trimmed.
  // The stale check is always uncapped: a trimmed list would make live
  // comments look stale.
  final maxIssues = staleMode
      ? 0
      : parsed.maxIssues ??
            int.tryParse(Platform.environment['SAROPA_LINTS_MAX'] ?? '') ??
            0;

  // --quiet: suppress ALL stderr progress/status from the scanner by routing
  // messages to a no-op sink. The caller gets only the exit code + stdout.
  final runner = ScanRunner(
    targetPath: path,
    dartFiles: dartFiles.isEmpty ? null : dartFiles,
    tier: tier,
    debugRule: parsed.debugRule,
    excludeLightLane: parsed.excludeLightLane,
    // --lane full|light: explicit lane override. parseRuleLane handles null
    // (defaults to light for the plugin, but ScanRunner defaults to full).
    lane: parseRuleLane(parsed.lane ?? 'full'),
    laneStats: parsed.laneStats,
    messageSink: parsed.quiet && parsed.progress != 'json' ? (_) {} : null,
    maxIssues: maxIssues,
    excludeGlobs: excludeGlobs,
    includeGlobs: parsed.includeGlobs,
    // When the user explicitly names files via --files, honor that intent —
    // don't silently drop them because they sit under an excluded path
    // (example/, bin/, etc.). Same rationale as the LSP server's false.
    applyExclusionsToFileList: dartFiles.isEmpty,
    // --no-exclude disables all hardcoded path exclusions (example/, build/,
    // .dart_tool/, etc.) so the scan covers every .dart file it finds.
    noExclude: parsed.noExclude,
  );
  // --find-stale-ignores / --fix-stale-ignores: their own scan, resolved and
  // in-process, with every finding reported and coverage recorded. Both
  // helpers call exit() themselves; find wins when both flags are given.
  if (staleMode) {
    final scan = await runStaleIgnoreScan(runner);
    if (scan == null) exit(2);
    final files = _staleIgnoreFiles(
      path,
      dartFiles,
      excludeGlobs,
      parsed.includeGlobs,
    );
    if (parsed.findStaleIgnores) {
      _runFindStaleIgnores(
        scan,
        files,
        path,
        formatJson,
        parsed.jsonFilePath,
        quiet,
      );
    }
    _runFixStaleIgnores(scan, files, path, quiet);
  }

  // --resolve runs the slower, fully-resolved scan so that
  // InstanceCreationExpression and type-based rules actually fire; the default
  // path stays the fast syntactic parse.
  // --check-accepted always resolves: list entries record findings seen in the
  // editor, which is resolved, so a syntactic run would call an entry for a
  // type-based rule stale and fail CI on a finding that still exists.
  final useResolve = parsed.resolve || parsed.checkAccepted;
  final List<ScanDiagnostic>? diagnostics;
  {
    // Worker count and memory budget. Resolution order: --jobs, then the
    // SAROPA_LINTS_JOBS env var, then the default (auto for the cheap
    // syntactic scan; serial for --resolve, which opts in explicitly).
    final env = Platform.environment;
    final envJobs = env['SAROPA_LINTS_JOBS'];
    final requested =
        parsed.jobs ?? (envJobs == null ? null : parseJobsValue(envJobs));
    final envMem = int.tryParse(env['SAROPA_LINTS_MAX_MEMORY_MB'] ?? '');
    final machine = detectMachine();
    final jobsDecision = resolveJobs(
      requested: requested,
      fileCount: runner.countFilesToScan(),
      machine: machine,
      resolved: useResolve,
      incompatibleReason: parsed.profile
          ? '--profile records timings per process'
          : parsed.debugRule != null
          ? '--debug-rule traces in one process'
          : null,
    );
    final progressStyle = switch (parsed.progress) {
      'bar' => ProgressStyle.bar,
      'plain' => ProgressStyle.plain,
      'json' => ProgressStyle.json,
      'none' => ProgressStyle.none,
      _ => ProgressStyle.auto,
    };
    if (!quiet || progressStyle == ProgressStyle.json) {
      for (final note in jobsDecision.notes) {
        stderr.writeln(note);
      }
    }
    diagnostics = await runner.runParallel(
      jobsDecision.jobs,
      resolve: useResolve,
      config: ScanParallelConfig(
        maxMemoryMb: parsed.maxMemoryMb ?? envMem,
        availableMemoryMb: machine.availableMemoryMb,
        totalMemoryMb: machine.totalMemoryMb,
        chunkTimeout: Duration(seconds: parsed.chunkTimeoutSeconds ?? 120),
        slowFileMs: parsed.slowFileMs ?? 3000,
        progress: progressStyle,
        hasTerminal: stdout.hasTerminal && stderr.hasTerminal,
        // An explicit memory budget must be enforced even with one worker,
        // and the in-process serial path has no watchdog.
        forceEngine:
            (parsed.maxMemoryMb ?? envMem) != null &&
            jobsDecision.jobs <= 1 &&
            !parsed.profile &&
            parsed.debugRule == null,
      ),
    );
  }

  // Flush the timing profile even when diagnostics is null (config error):
  // by that point rules may already have run, and a partial profile beats a
  // silently discarded one. Written to stderr so --format json stdout stays
  // machine-parseable.
  if (parsed.profile) {
    final timingPath = writeRuleTimingReport(
      projectRoot: path,
      tier: tier,
      resolved: useResolve,
      fileCount: dartFiles.isEmpty ? null : dartFiles.length,
    );
    if (timingPath != null) {
      if (!quiet) stderr.writeln('Timing profile: $timingPath');
    } else {
      // An empty tracker after a profiled run means no rule callbacks
      // executed — surface it, never let profiling fail silently again.
      // Braced: the call wraps to a second line, which the
      // curly_braces_in_flow_control_structures lint rejects without a block.
      if (!quiet) {
        stderr.writeln('Timing profile: no data collected (no rules ran).');
      }
    }
  }

  if (diagnostics == null) {
    exit(2);
  }

  // Exit non-zero when explicitly requested files were skipped for being
  // outside the analysis context root — a silent skip on exit 0 lets CI pass
  // having scanned nothing. Only applies to --files / --files-from-stdin
  // (directory discovery never produces out-of-root paths).
  final skipped = runner.skippedFileCount;
  if (skipped > 0 && dartFiles.isNotEmpty) {
    if (!quiet) {
      stderr.writeln(
        '$skipped of ${dartFiles.length} requested file(s) skipped '
        '(outside analysis roots).',
      );
    }
    // All requested files skipped → exit 2 (input error, same as no-config).
    // Check the count, not diagnostics.isEmpty — a partial skip where the
    // scanned files had no findings is exit 1, not exit 2.
    // --strict-files: ANY skip is a hard error (exit 2), not just all-skipped.
    if (skipped >= dartFiles.length || parsed.strictFiles) exit(2);
  }

  // Honor // ignore: and // ignore_for_file: directives by filtering
  // diagnostics that the user has explicitly suppressed. The reporter
  // already drops most of them; this also covers findings its own checks do
  // not see (e.g. offset-only reports).
  final scannedFiles = dartFiles.isNotEmpty
      ? dartFiles
            .map(
              (f) => p.isAbsolute(f)
                  ? p.normalize(f)
                  : p.normalize(p.join(p.absolute(path), f)),
            )
            .where((f) => f.endsWith('.dart'))
            .toList()
      : ScanRunner.discoverDartFiles(
          p.absolute(path),
          excludeGlobs: excludeGlobs,
          includeGlobs: parsed.includeGlobs,
        );
  // --check-accepted also scans the files list entries name that discovery
  // skipped (example/, bin/, generated), so those entries get a verdict. Not
  // with --files: that run is scoped on purpose.
  var extra = SkippedFilesScan();
  if (parsed.checkAccepted && dartFiles.isEmpty) {
    final target = p.absolute(path);
    extra = await scanAcceptedSkippedFiles(
      target: target,
      filesByRoot: acceptedSkippedFiles(
        target: target,
        lists: AcceptedListSet(),
        alreadyScanned: scannedFiles,
        // Only the user's own globs: analyzer excludes such as example/** are
        // what hid these files, and their lists are still read by the editor.
        excludeGlobs: parsed.excludeGlobs,
      ),
      runnerFor: (configRoot, files) => ScanRunner(
        targetPath: configRoot,
        dartFiles: files,
        tier: tier,
        debugRule: parsed.debugRule,
        excludeLightLane: parsed.excludeLightLane,
        lane: parseRuleLane(parsed.lane ?? 'full'),
        messageSink: quiet ? (_) {} : null,
        maxIssues: maxIssues,
        // The files were chosen above; also lets an analyzer-excluded file
        // get its own context instead of being skipped.
        applyExclusionsToFileList: false,
      ),
    );
  }

  final ignoreFiltered = filterIgnoredDiagnostics(
    diagnostics: [...diagnostics, ...extra.diagnostics],
    files: [...scannedFiles, ...extra.files],
  );

  // Accepted-findings lists (saropa_accepted.yaml beside each package's
  // pubspec.yaml): drop findings an entry covers from every output below.
  // Each finding uses the list of its own nearest package, the same rule the
  // analyzer plugin applies, so a nested package (example/) is filtered by its
  // own list, not the outer one. Applied after the ignore filter so an entry
  // whose findings are all `// ignore:`d counts as hiding nothing (and shows
  // up as stale, i.e. redundant).
  final acceptedLists = AcceptedListSet();
  // Loaded up front so a broken list at the target's own package is warned
  // about even when no finding falls in it, as before per-package lists.
  if (acceptedRootForDir(p.absolute(path)) case final targetRoot?) {
    acceptedLists.listAt(targetRoot);
  }
  final acceptedSplit = filterAcceptedByNearestRoot(
    ignoreFiltered,
    lists: acceptedLists,
  );

  // --check-accepted: report every list under the target (hidden count,
  // stale, invalid) and exit. Runs here, after both filters, so it judges the
  // same finding set the normal output would have shown.
  if (parsed.checkAccepted) {
    // An in-process run records which files it really walked; a file it could
    // not resolve or never reached (memory stop) must not count as checked.
    // Worker runs report their skips through lastParallelReport instead.
    final walked = runner.lastParallelReport == null
        ? {for (final f in runner.walkedFiles) rootKey(canonicalRoot(f))}
        : null;
    _runCheckAccepted(
      target: p.absolute(path),
      lists: acceptedLists,
      split: acceptedSplit,
      scannedFiles: [
        for (final f in scannedFiles)
          if (walked == null || walked.contains(rootKey(canonicalRoot(f)))) f,
        ...extra.files,
      ],
      ranRules: runner.ranRuleNames,
      rulesRunByFile: extra.rulesByFile,
      // Trimmed or aborted output may be missing findings, so "no finding"
      // cannot be trusted as stale in that case.
      complete:
          maxIssues <= 0 && !(runner.lastParallelReport?.aborted ?? false),
      skippedFiles: runner.lastParallelReport?.skippedFiles ?? const [],
      formatJson: formatJson,
      jsonFilePath: parsed.jsonFilePath,
      quiet: quiet,
    );
    // _runCheckAccepted calls exit() internally.
  }

  // A broken list hides nothing; say so instead of failing silently. Not an
  // exit-code change: only --check-accepted gates on list health.
  if (!quiet) {
    for (final broken in acceptedLists.withProblems) {
      stderr.writeln(
        'Warning: ${broken.path} has ${broken.problems.length} problem(s); '
        'invalid entries hide nothing. Run with --check-accepted for details.',
      );
    }
  }
  final effectiveDiagnostics = acceptedSplit.kept;

  // Warn about unrecognized severity values so a future analyzer change
  // doesn't silently drop diagnostics through the rank-0 fallback.
  if (parsed.minSeverity != null) {
    final unknown = effectiveDiagnostics
        .map((d) => d.severity.toUpperCase())
        .where((s) => !_knownSeverities.contains(s))
        .toSet();
    for (final s in unknown) {
      // Braced for the same multi-line-statement lint as above.
      if (!quiet) {
        stderr.writeln(
          'Warning: unrecognized severity "$s" — excluded by filter.',
        );
      }
    }
  }

  // Apply --min-severity / --max-severity / --min-impact filters to exclude
  // diagnostics outside the requested window.
  final hasFilter =
      parsed.minSeverity != null ||
      parsed.maxSeverity != null ||
      parsed.minImpact != null;
  final filtered = hasFilter
      ? effectiveDiagnostics.where((d) {
          final rank = _severityRank(d.severity);
          if (parsed.minSeverity != null &&
              rank < _severityRank(parsed.minSeverity!)) {
            return false;
          }
          if (parsed.maxSeverity != null &&
              rank > _severityRank(parsed.maxSeverity!)) {
            return false;
          }
          // Impact filter: uses the same rank scale as severity but against the
          // rule-declared impact. Diagnostics with no impact (non-saropa rules)
          // are excluded when a minimum impact is set, since they cannot be
          // classified.
          if (parsed.minImpact != null) {
            final impact = d.impact;
            if (impact == null ||
                _severityRank(impact) < _severityRank(parsed.minImpact!)) {
              return false;
            }
          }
          return true;
        }).toList()
      : effectiveDiagnostics;

  // --fail-on / --fail-on-impact decouple exit code from display filtering:
  // the exit code is determined by whether any diagnostic in the ignore-
  // filtered set meets the threshold, not by what survived the severity
  // display filter. Ignored diagnostics (// ignore:) are excluded from both.
  // Build the tier rule set once if --fail-on-tier is active, so the exit-code
  // check doesn't recompute it per diagnostic.
  final failOnTierRules = parsed.failOnTier != null
      ? getRulesForTier(parsed.failOnTier!)
      : null;

  // Promote exit code to 1 when explicitly requested files were skipped, so
  // CI never passes having silently dropped part of the requested scope.
  var exitCode = _computeExitCode(
    filtered: filtered,
    allDiagnostics: effectiveDiagnostics,
    failOn: parsed.failOn,
    failOnImpact: parsed.failOnImpact,
    failOnTierRules: failOnTierRules,
    failOnCount: parsed.failOnCount,
    failOnImpactCount: parsed.failOnImpactCount,
  );
  if (skipped > 0 && dartFiles.isNotEmpty && exitCode == 0) {
    exitCode = 1;
  }
  // A scan that stopped early to protect the machine (memory pressure) has
  // only partial results: never let a gate pass on that. Exit 3 means
  // "incomplete" and is distinct from 1 (findings) and 2 (config error);
  // findings, if any, still win with exit 1.
  final parallelReport = runner.lastParallelReport;
  if (parallelReport != null && parallelReport.aborted && exitCode == 0) {
    exitCode = 3;
  }

  // Build --fail-on metadata for JSON output so consumers understand why
  // the exit code may disagree with an empty diagnostics array.
  // BREAKING for consumers that check `failOn == null`: this object is now
  // non-null when --fail-on-impact or --fail-on-tier is used alone. The
  // `threshold` key is still absent in that case — check for it specifically.
  final failOnMeta =
      parsed.failOn != null ||
          parsed.failOnImpact != null ||
          parsed.failOnTier != null
      ? <String, Object>{
          // Severity threshold (original --fail-on).
          if (parsed.failOn != null) 'threshold': parsed.failOn!,
          // Impact threshold (new --fail-on-impact).
          if (parsed.failOnImpact != null)
            'impactThreshold': parsed.failOnImpact!,
          // Tier threshold (--fail-on-tier).
          if (parsed.failOnTier != null) 'tierThreshold': parsed.failOnTier!,
          'thresholdMet': exitCode == 1,
          // Include the count baselines when active.
          if (parsed.failOnCount != null) 'countBaseline': parsed.failOnCount!,
          if (parsed.failOnImpactCount != null)
            'impactCountBaseline': parsed.failOnImpactCount!,
        }
      : null;

  if (filtered.isEmpty) {
    if (!formatJson) {
      // Distinguish "genuinely clean" from "all outside window" so callers
      // (AI agents, CI) know diagnostics were suppressed, not absent.
      if (hasFilter && effectiveDiagnostics.isNotEmpty) {
        print(
          '\nNo issues in the requested filter window '
          '(${effectiveDiagnostics.length} outside threshold).',
        );
      } else {
        print('\nNo issues found.');
      }
    }
    // When a --fail-on* flag causes a non-zero exit despite no displayed
    // diagnostics, explain so automation doesn't see "No issues" + exit 1.
    if (!formatJson &&
        exitCode != 0 &&
        (parsed.failOn != null ||
            parsed.failOnImpact != null ||
            parsed.failOnTier != null)) {
      final reasons = [
        if (parsed.failOn != null) '--fail-on ${parsed.failOn!.toLowerCase()}',
        if (parsed.failOnImpact != null)
          '--fail-on-impact ${parsed.failOnImpact!.toLowerCase()}',
        if (parsed.failOnTier != null) '--fail-on-tier ${parsed.failOnTier!}',
      ];
      print(
        '(exit 1: ${reasons.join(' or ')} threshold met '
        'in unfiltered diagnostics)',
      );
    }
    if (formatJson) {
      _writeJson(
        scanDiagnosticsToJsonString(filtered, failOn: failOnMeta),
        parsed.jsonFilePath,
        quiet: quiet,
      );
    }
    exit(exitCode);
  }

  if (formatJson) {
    _writeJson(
      scanDiagnosticsToJsonString(filtered, failOn: failOnMeta),
      parsed.jsonFilePath,
      quiet: quiet,
    );
    exit(exitCode);
  }

  final reportPath = _writeReport(filtered, path);
  _printSummary(filtered);
  print('Report: $reportPath');
  exit(exitCode);
}

/// Reads stdin until EOF; returns non-empty trimmed lines (for --files-from-stdin).
List<String> _readStdinLines() {
  final lines = <String>[];
  String? line;
  while ((line = stdin.readLineSync()) != null) {
    final trimmed = line!.trim();
    if (trimmed.isNotEmpty) lines.add(trimmed);
  }
  return lines;
}

/// Write detailed results to a report file. Returns the file path.
String _writeReport(List<ScanDiagnostic> diagnostics, String targetPath) {
  // Fix: prefer_utc_for_storage — report timestamps are written to files and
  // consumed across time zones; UTC keeps filename ordering stable.
  final now = DateTime.now().toUtc();
  final ts =
      '${now.year}${now.month.toString().padLeft(2, '0')}${now.day.toString().padLeft(2, '0')}_'
      '${now.hour.toString().padLeft(2, '0')}${now.minute.toString().padLeft(2, '0')}${now.second.toString().padLeft(2, '0')}';
  final dateFolder = ts.prefix(8);

  final reportsDir = Directory('reports/$dateFolder');
  if (!reportsDir.existsSync()) {
    reportsDir.createSync(recursive: true);
  }

  final reportFile = File('${reportsDir.path}/${ts}_scan_report.log');

  final buf = StringBuffer();
  buf.writeln('${'=' * 80}');
  buf.writeln('SAROPA LINTS SCAN REPORT');
  // Fix: prefer_utc_for_storage — explicit .toUtc() at the call site so the
  // rule can see timezone normalization at the storage-adjacent usage.
  buf.writeln('Generated: ${now.toUtc().toIso8601String()}');
  buf.writeln('Target: ${p.absolute(targetPath)}');
  buf.writeln('Total issues: ${diagnostics.length}');
  buf.writeln('${'=' * 80}');
  buf.writeln();

  // Group by file
  final byFile = <String, List<ScanDiagnostic>>{};
  for (final d in diagnostics) {
    byFile.putIfAbsent(d.filePath, () => []).add(d);
  }

  for (final entry in byFile.entries) {
    buf.writeln(entry.key);
    for (final d in entry.value) {
      // Default nullable problemMessage to empty string (avoid_nullable_interpolation).
      buf.writeln(
        '  ${d.severity.padRight(7)} '
        'line ${d.line.toString().padLeft(4)}  '
        '${d.ruleName}  ${d.problemMessage ?? ''}',
      );
    }
    buf.writeln();
  }

  // Summary by rule
  buf.writeln('${'─' * 80}');
  buf.writeln('ISSUES BY RULE');
  buf.writeln('${'─' * 80}');
  final byRule = <String, int>{};
  for (final d in diagnostics) {
    byRule[d.ruleName] = (byRule[d.ruleName] ?? 0) + 1;
  }

  final sortedRules = byRule.entries.toList()
    ..sort((a, b) => b.value.compareTo(a.value));
  for (final entry in sortedRules) {
    buf.writeln('  ${entry.value.toString().padLeft(6)}  ${entry.key}');
  }

  reportFile.writeAsStringSync(buf.toString());
  return reportFile.path;
}

/// Print a compact summary to terminal.
void _printSummary(List<ScanDiagnostic> diagnostics) {
  // Count by severity
  final bySeverity = <String, int>{};
  for (final d in diagnostics) {
    bySeverity[d.severity] = (bySeverity[d.severity] ?? 0) + 1;
  }

  // Count by rule (for top offenders)
  final byRule = <String, int>{};
  for (final d in diagnostics) {
    byRule[d.ruleName] = (byRule[d.ruleName] ?? 0) + 1;
  }

  // Count files affected
  final fileCount = diagnostics.map((d) => d.filePath).toSet().length;

  print('');
  print('${diagnostics.length} issue(s) in $fileCount file(s)');

  final parts = <String>[];
  for (final sev in ['ERROR', 'WARNING', 'INFO']) {
    final count = bySeverity[sev];
    if (count != null && count > 0) {
      parts.add('$count ${sev.toLowerCase()}');
    }
  }
  if (parts.isNotEmpty) {
    print('  ${parts.join(' · ')}');
  }

  // Top 10 rules
  final sortedRules = byRule.entries.toList()
    ..sort((a, b) => b.value.compareTo(a.value));
  final top = sortedRules.take(10);
  print('');
  print('Top rules:');
  for (final entry in top) {
    print('  ${entry.value.toString().padLeft(6)}  ${entry.key}');
  }
  if (sortedRules.length > 10) {
    print('  ... and ${sortedRules.length - 10} more (see report)');
  }
  print('');
}

/// Decides what a plain scan does when [root]'s plugin block is commented out.
///
/// Exits 0 with a "scan skipped" line when the project is switched off, or when
/// the block holds no rule settings to scan with (nothing to run, and hooks
/// must not start failing). Otherwise returns, so the scan runs with the
/// commented-out settings: the language server (on by default) comments the
/// block out while saropa_lints stays in use. A live rule list, or no marker,
/// returns without output.
void _handleCommentedOutPluginBlock(String root, {required bool quiet}) {
  if (!hasCommentedOutPluginBlock(root) ||
      loadScanConfig(root, includeDisabledBlock: false) != null) {
    return;
  }
  if (isScanIntegrationDisabled(root)) {
    print('saropa_lints is turned off for this project; scan skipped.');
    exit(0);
  }
  if (loadScanConfig(root) == null) {
    print(
      'saropa_lints plugin block is commented out and holds no rule '
      'settings; scan skipped.',
    );
    exit(0);
  }
  // stderr so --format json stdout stays parseable.
  if (!quiet) {
    stderr.writeln(
      'Plugin block is commented out; scanning with its rule settings. To '
      'skip, set "saropaLints.enabled": false in .vscode/settings.json.',
    );
  }
}

void _runFixIgnores(String targetPath) {
  final allRules = getAllDefinedRules();
  final results = convertIgnoreComments(
    allRules,
    false,
    targetDir: p.canonicalize(targetPath),
  );
  if (results.isEmpty) {
    print('No bare ignore comments found.');
    return;
  }
  final total = results.values.fold(0, (s, c) => s + c);
  print('Converted $total ignore comments in ${results.length} files:');
  for (final entry in results.entries) {
    print('  ${entry.value} in ${p.relative(entry.key)}');
  }
}

/// The `.dart` files the stale-ignore modes read comments from: [dartFiles]
/// when given, otherwise every file discovered under [targetPath]. Same
/// resolution as the scan itself, so no comment outside the scan is judged
/// (and any file the scan did not walk is kept by its coverage check).
List<String> _staleIgnoreFiles(
  String targetPath,
  List<String> dartFiles,
  List<String> excludeGlobs,
  List<String> includeGlobs,
) {
  if (dartFiles.isEmpty) {
    return ScanRunner.discoverDartFiles(
      p.absolute(targetPath),
      excludeGlobs: excludeGlobs,
      includeGlobs: includeGlobs,
    );
  }
  return dartFiles
      .map(
        (f) => p.isAbsolute(f)
            ? p.normalize(f)
            : p.normalize(p.join(p.absolute(targetPath), f)),
      )
      .where((f) => f.endsWith('.dart'))
      .toList();
}

/// Stale comments in [files], judged only where [scan] has positive evidence
/// (rule ran, file fully walked). Tells the user, on stderr so JSON stdout
/// stays clean, how many files were kept unjudged because the scan did not
/// cover them.
List<StaleIgnore> _detectStale(
  StaleIgnoreScan scan,
  List<String> files, {
  required bool quiet,
}) {
  final uncovered = files.length - scan.coverage.walkedCount(files);
  if (uncovered > 0 && !quiet) {
    stderr.writeln(
      '$uncovered file(s) could not be fully scanned; their ignore comments '
      'were kept.',
    );
  }
  return detectStaleIgnores(
    diagnostics: scan.diagnostics,
    files: files,
    coverage: scan.coverage,
  );
}

/// Detects stale `// ignore:` comments by comparing ignore directives against
/// the diagnostics the stale scan produced. An ignore is stale when its rule
/// ran on the file and did not fire on the target line.
void _runFindStaleIgnores(
  StaleIgnoreScan scan,
  List<String> files,
  String targetPath,
  bool formatJson,
  String? jsonFilePath,
  bool quiet,
) {
  final stale = _detectStale(scan, files, quiet: quiet);

  if (formatJson) {
    _writeJson(staleIgnoresToJsonString(stale), jsonFilePath, quiet: quiet);
    exit(stale.isEmpty ? 0 : 1);
  }

  if (stale.isEmpty) {
    print('\nNo stale ignore comments found.');
    exit(0);
  }

  // Group by file for readable text output.
  final byFile = <String, List<StaleIgnore>>{};
  for (final s in stale) {
    byFile.putIfAbsent(s.filePath, () => []).add(s);
  }

  final fileCount = byFile.length;
  print('');
  print('${stale.length} stale ignore(s) in $fileCount file(s):');
  print('');

  for (final entry in byFile.entries) {
    print(p.relative(entry.key, from: targetPath));
    for (final s in entry.value) {
      print(
        '  line ${s.commentLine.toString().padLeft(4)}  '
        '${s.ruleName}  (target line ${s.targetLine})',
      );
    }
    print('');
  }

  // Top rules summary for quick triage.
  final byRule = <String, int>{};
  for (final s in stale) {
    byRule[s.ruleName] = (byRule[s.ruleName] ?? 0) + 1;
  }
  final sortedRules = byRule.entries.toList()
    ..sort((a, b) => b.value.compareTo(a.value));
  print('By rule:');
  for (final entry in sortedRules) {
    print('  ${entry.value.toString().padLeft(6)}  ${entry.key}');
  }
  print('');

  exit(1);
}

/// Reports every `saropa_accepted.yaml` under [target] for `--check-accepted`
/// and exits: 1 when any entry is stale or invalid (CI gate), else 0. Never
/// edits a list — removal is a reviewed decision, not an automatic one.
void _runCheckAccepted({
  required String target,
  required AcceptedListSet lists,
  required AcceptedSplit split,
  required List<String> scannedFiles,
  required Set<String> ranRules,
  required Map<String, Set<String>> rulesRunByFile,
  required bool complete,
  required List<String> skippedFiles,
  required bool formatJson,
  required String? jsonFilePath,
  required bool quiet,
}) {
  // Files a worker skipped (timeout, crash) were not really scanned, so an
  // entry on one of them must stay "not checked" rather than turn stale.
  final skipped = {for (final f in skippedFiles) rootKey(canonicalRoot(f))};
  final checks = checkAcceptedLists(
    target: target,
    lists: lists,
    split: split,
    scannedFiles: [
      for (final f in scannedFiles)
        if (!skipped.contains(rootKey(canonicalRoot(f)))) f,
    ],
    rulesRun: ranRules,
    rulesRunByFile: rulesRunByFile,
    complete: complete,
  );
  if (formatJson) {
    _writeJson(acceptedCheckToJsonString(checks), jsonFilePath, quiet: quiet);
  } else {
    print('');
    acceptedCheckToText(checks).forEach(print);
  }
  exit(acceptedCheckFails(checks) ? 1 : 0);
}

/// Detects stale `// ignore:` comments and automatically removes them from
/// the source files. Prints a summary of what was fixed. Uses the same
/// evidence-gated detection as [_runFindStaleIgnores], so a comment is only
/// removed when the scan proved it unneeded.
void _runFixStaleIgnores(
  StaleIgnoreScan scan,
  List<String> files,
  String targetPath,
  bool quiet,
) {
  final stale = _detectStale(scan, files, quiet: quiet);

  if (stale.isEmpty) {
    print('\nNo stale ignore comments found. Nothing to fix.');
    exit(0);
  }

  // Apply the fixes — removes stale directives from source files.
  final results = fixStaleIgnores(stale);

  if (results.isEmpty) {
    // Detection found stale ignores but the fixer couldn't modify any files
    // (e.g. files were deleted between detection and fix).
    print(
      '\nDetected ${stale.length} stale ignore(s) but no files were modified.',
    );
    exit(1);
  }

  // Summary: total removed and files touched.
  final totalRemoved = results.fold(0, (sum, r) => sum + r.removedCount);
  final fileCount = results.length;
  print('');
  print('Fixed $totalRemoved stale ignore(s) in $fileCount file(s):');
  print('');
  for (final r in results) {
    print(
      '  ${r.removedCount} removed in ${p.relative(r.filePath, from: targetPath)}',
    );
  }
  print('');

  exit(0);
}

/// Writes JSON output to [filePath] if set, otherwise prints to stdout.
/// Using a file avoids the stdout-redirection problem entirely (#310).
/// Creates parent directories if they don't exist — fail-fast on
/// permission errors, but don't force callers to mkdir first.
void _writeJson(String json, String? filePath, {bool quiet = false}) {
  if (filePath != null) {
    final file = File(filePath);
    final parent = file.parent;
    if (!parent.existsSync()) {
      parent.createSync(recursive: true);
    }
    file.writeAsStringSync(json);
    if (!quiet) stderr.writeln('JSON written to: $filePath');
  } else {
    print(json);
  }
}

/// Known severity strings emitted by the analyzer diagnostic system.
const _knownSeverities = {'ERROR', 'WARNING', 'INFO'};

/// Severity rank for ordering/filtering: higher = more severe.
/// The fallback `_ => 0` handles the analyzer's NONE severity (never used in
/// practice for diagnostics) — such entries are excluded by any filter, which
/// is safe because no real lint rule emits NONE.
int _severityRank(String severity) => switch (severity.toUpperCase()) {
  'ERROR' => 3,
  'WARNING' => 2,
  'INFO' => 1,
  _ => 0,
};

/// Returns true if [severity] is at or above [minSeverity].
bool _meetsMinSeverity(String severity, String minSeverity) =>
    _severityRank(severity) >= _severityRank(minSeverity);

/// Determines exit code based on diagnostics and the optional --fail-on /
/// --fail-on-impact thresholds.
///
/// Without either: exit 1 when any filtered diagnostic exists (existing
/// behavior). With --fail-on: exit 1 when the FULL diagnostic list has enough
/// entries at/above the severity threshold. With --fail-on-impact: same logic
/// but checks the rule's declared impact instead. When both are set, either
/// threshold being met triggers exit 1 (logical OR — strictest wins).
/// [failOnCount] applies to --fail-on (severity count baseline).
/// [failOnImpactCount] applies to --fail-on-impact (impact count baseline).
/// [failOnTierRules] is the pre-computed set from [getRulesForTier] when
/// --fail-on-tier is active — diagnostics whose ruleName is in this set
/// trigger exit 1.
int _computeExitCode({
  required List<ScanDiagnostic> filtered,
  required List<ScanDiagnostic> allDiagnostics,
  required String? failOn,
  String? failOnImpact,
  Set<String>? failOnTierRules,
  int? failOnCount,
  int? failOnImpactCount,
}) {
  // Track whether any threshold triggers a failure (logical OR).
  var triggered = false;

  if (failOn != null) {
    // Count diagnostics in the full set that meet the severity threshold.
    final matchCount = allDiagnostics
        .where((d) => _meetsMinSeverity(d.severity, failOn))
        .length;
    // Without --fail-on-count: any match → exit 1 (count > 0).
    // With --fail-on-count: exit 1 only when count exceeds the baseline.
    final threshold = failOnCount ?? 0;
    if (matchCount > threshold) triggered = true;
  }

  if (failOnImpact != null) {
    // Count saropa diagnostics whose rule-declared impact meets the threshold.
    // Non-saropa diagnostics (impact == null) are excluded — they have no
    // declared impact and cannot be classified on this axis.
    // Note: impact values come from LintImpact.name (lowercase: error/warning/info)
    // while failOnImpact is uppercased by the parser — _severityRank handles
    // both cases via .toUpperCase() internally.
    final impactMatchCount = allDiagnostics
        .where(
          (d) => d.impact != null && _meetsMinSeverity(d.impact!, failOnImpact),
        )
        .length;
    // Without --fail-on-impact-count: any match → exit 1 (count > 0).
    // With --fail-on-impact-count: exit 1 only when count exceeds baseline.
    final impactThreshold = failOnImpactCount ?? 0;
    if (impactMatchCount > impactThreshold) triggered = true;
  }

  if (failOnTierRules != null) {
    // Check if any diagnostic comes from a rule in the target tier.
    // Rule names in diagnostics use the bare name (no saropa_lints/ prefix),
    // which matches the tiers.dart sets.
    final tierMatchCount = allDiagnostics
        .where((d) => failOnTierRules.contains(d.ruleName))
        .length;
    if (tierMatchCount > 0) triggered = true;
  }

  // When any threshold is active, use the triggered result.
  if (failOn != null || failOnImpact != null || failOnTierRules != null) {
    return triggered ? 1 : 0;
  }

  // Default: any displayed diagnostic → exit 1.
  return filtered.isEmpty ? 0 : 1;
}

